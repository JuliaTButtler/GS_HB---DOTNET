-- 1. USUARIO_HB
CREATE TABLE USUARIO_HB (
    ID              NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    NOME            VARCHAR2(120) NOT NULL,
    EMAIL           VARCHAR2(180) NOT NULL,
    SENHA_HASH      VARCHAR2(255) NOT NULL,
    PAPEL           VARCHAR2(20)  NOT NULL,
    ATIVO           CHAR(1) DEFAULT 'S' NOT NULL,
    CRIADO_EM       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT UQ_USUARIO_HB_EMAIL
        UNIQUE (EMAIL),

    CONSTRAINT CHK_USUARIO_HB_PAPEL
        CHECK (PAPEL IN ('CIDADAO', 'GESTOR')),

    CONSTRAINT CHK_USUARIO_HB_ATIVO
        CHECK (ATIVO IN ('S', 'N'))
);

COMMENT ON TABLE USUARIO_HB IS
'HidroBairro: usuarios do app. Dominio JAVA (auth/JWT). .NET apenas referencia por FK.';

COMMENT ON COLUMN USUARIO_HB.PAPEL IS
'CIDADAO ou GESTOR (sem acento para evitar problema de charset no CHECK).';


-- 2. PONTO_MONITORAMENTO_HB
CREATE TABLE PONTO_MONITORAMENTO_HB (
    ID                  NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    NOME                VARCHAR2(120) NOT NULL,
    SUBPREFEITURA       VARCHAR2(80)  NOT NULL,
    BAIRRO              VARCHAR2(80)  NOT NULL,
    ZONA                VARCHAR2(20)  DEFAULT 'SUL' NOT NULL,
    LATITUDE            NUMBER(10,7)  NOT NULL,
    LONGITUDE           NUMBER(10,7)  NOT NULL,
    LIMIAR_ALERTA_CM    NUMBER(8,2)   NOT NULL,
    ATIVO               CHAR(1) DEFAULT 'S' NOT NULL,
    CRIADO_EM           TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT CHK_PONTO_HB_ATIVO
        CHECK (ATIVO IN ('S', 'N')),

    CONSTRAINT CHK_PONTO_HB_ZONA
        CHECK (ZONA IN ('SUL', 'LESTE', 'NORTE', 'OESTE', 'CENTRO')),

    CONSTRAINT CHK_PONTO_HB_LIMIAR
        CHECK (LIMIAR_ALERTA_CM > 0)
);

COMMENT ON TABLE PONTO_MONITORAMENTO_HB IS
'HidroBairro: pontos de sensor/monitoramento (Campo Limpo, Capao, MBoi). Dominio JAVA.';


-- 3. LEITURA_HB
CREATE TABLE LEITURA_HB (
    ID              NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    PONTO_ID        NUMBER NOT NULL,
    NIVEL_CM        NUMBER(8,2) NOT NULL,
    COLETADO_EM     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ORIGEM          VARCHAR2(20) NOT NULL,

    CONSTRAINT FK_LEITURA_HB_PONTO
        FOREIGN KEY (PONTO_ID)
        REFERENCES PONTO_MONITORAMENTO_HB(ID),

    CONSTRAINT CHK_LEITURA_HB_ORIGEM
        CHECK (ORIGEM IN ('IOT', 'SIMULADO')),

    CONSTRAINT CHK_LEITURA_HB_NIVEL
        CHECK (NIVEL_CM >= 0)
);

COMMENT ON TABLE LEITURA_HB IS
'HidroBairro: leituras de nivel (cm). Dominio JAVA. Origem IOT ou SIMULADO.';


-- 4. ALERTA_HB
CREATE TABLE ALERTA_HB (
    ID              NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    PONTO_ID        NUMBER NOT NULL,
    LEITURA_ID      NUMBER NULL,
    NIVEL_CM        NUMBER(8,2) NOT NULL,
    SEVERIDADE      VARCHAR2(20) NOT NULL,
    MENSAGEM        VARCHAR2(400) NOT NULL,
    STATUS          VARCHAR2(20) DEFAULT 'ATIVO' NOT NULL,
    CRIADO_EM       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ENCERRADO_EM    TIMESTAMP NULL,

    CONSTRAINT FK_ALERTA_HB_PONTO
        FOREIGN KEY (PONTO_ID)
        REFERENCES PONTO_MONITORAMENTO_HB(ID),

    CONSTRAINT FK_ALERTA_HB_LEITURA
        FOREIGN KEY (LEITURA_ID)
        REFERENCES LEITURA_HB(ID),

    CONSTRAINT CHK_ALERTA_HB_SEVERIDADE
        CHECK (SEVERIDADE IN ('ATENCAO', 'CRITICO')),

    CONSTRAINT CHK_ALERTA_HB_STATUS
        CHECK (STATUS IN ('ATIVO', 'ENCERRADO')),

    CONSTRAINT CHK_ALERTA_HB_DATAS
        CHECK (
            ENCERRADO_EM IS NULL
            OR ENCERRADO_EM >= CRIADO_EM
        )
);

COMMENT ON TABLE ALERTA_HB IS
'HidroBairro: alertas de risco de alagamento. Dominio JAVA. Pode publicar evento RabbitMQ.';
